// Generates site/*.html (hostable pages) and src/content/legal.generated.ts (in-app copies) from the
// Markdown sources in legal/*.md, in every language that has a file: privacy.md is English,
// privacy.es.md Spanish, privacy.fr.md French, privacy.pt.md Portuguese. One source of truth per language.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const docs = [
  { key: 'privacy', file: 'privacy', titles: { en: 'Privacy Policy', es: 'Política de privacidad', fr: 'Politique de confidentialité', pt: 'Política de privacidade' } },
  { key: 'terms', file: 'terms', titles: { en: 'Terms of Use', es: 'Condiciones de uso', fr: 'Conditions d’utilisation', pt: 'Condições de utilização' } },
];
const languages = ['en', 'es', 'fr', 'pt'];
const footers = {
  en: ['Privacy Policy', 'Terms of Use', 'Data licences'],
  es: ['Política de privacidad', 'Condiciones de uso', 'Licencias de los datos'],
  fr: ['Politique de confidentialité', 'Conditions d’utilisation', 'Licences des données'],
  pt: ['Política de privacidade', 'Condições de utilização', 'Licenças dos dados'],
};

function escapeHtml(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function inline(text) {
  return escapeHtml(text).replace(/(https?:\/\/[^\s)]+)/g, '<a href="$1">$1</a>');
}

function markdownToHtml(md) {
  const blocks = md.split(/\n{2,}/).map((b) => b.trim()).filter(Boolean);
  return blocks
    .map((block) => {
      if (block.startsWith('# ')) return `<h1>${inline(block.slice(2))}</h1>`;
      if (block.startsWith('## ')) return `<h2>${inline(block.slice(3))}</h2>`;
      if (block.startsWith('### ')) return `<h3>${inline(block.slice(4))}</h3>`;
      if (block.startsWith('- ')) {
        const items = block.split('\n').map((l) => `<li>${inline(l.replace(/^- /, ''))}</li>`);
        return `<ul>${items.join('')}</ul>`;
      }
      return `<p>${inline(block.replace(/\n/g, ' '))}</p>`;
    })
    .join('\n');
}

function page(lang, file, title, body) {
  const suffix = lang === 'en' ? '' : `.${lang}`;
  const [privacy, terms, licences] = footers[lang];
  const switcher = languages.map((l) => (l === lang ? `<b>${l.toUpperCase()}</b>` : `<a href="${file}${l === 'en' ? '' : `.${l}`}.html">${l.toUpperCase()}</a>`)).join(' · ');
  return `<!doctype html>
<html lang="${lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Pumpwise · ${title}</title>
<style>
  :root { color-scheme: light dark; --bg:#F4F1EA; --fg:#121B26; --muted:#5A6372; --link:#9A5B00; --card:#FFFFFF; --border:#E0D9CB; }
  @media (prefers-color-scheme: dark) { :root { --bg:#0A0F15; --fg:#F3F0E8; --muted:#A4ACB7; --link:#FFC54D; --card:#131B24; --border:#24303C; } }
  body { margin:0; background:var(--bg); color:var(--fg); font:16px/1.6 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; }
  main { max-width: 720px; margin: 0 auto; padding: 32px 16px 64px; }
  article { background: var(--card); border: 1px solid var(--border); border-radius: 16px; padding: 24px; }
  h1 { font-size: 28px; letter-spacing: -0.5px; margin: 0 0 8px; }
  h2 { font-size: 20px; margin: 28px 0 8px; }
  h3 { font-size: 17px; margin: 20px 0 6px; }
  p, li { color: var(--fg); }
  a { color: var(--link); word-break: break-all; }
  nav { font-size: 14px; color: var(--muted); margin-bottom: 12px; }
  footer { color: var(--muted); font-size: 13px; margin-top: 24px; text-align: center; }
</style>
</head>
<body>
<main>
<nav>${switcher}</nav>
<article>
${body}
</article>
<footer><a href="privacy${suffix}.html">${privacy}</a> · <a href="terms${suffix}.html">${terms}</a> · <a href="data-licences.html">${licences}</a></footer>
</main>
</body>
</html>
`;
}

// HTML goes to site/, which the price-feed workflow publishes on GitHub Pages together with the feed.
const htmlDir = join(root, 'site');
mkdirSync(htmlDir, { recursive: true });

const generated = {};
const written = [];
for (const d of docs) {
  generated[d.key] = {};
  for (const lang of languages) {
    const source = join(root, 'legal', lang === 'en' ? `${d.file}.md` : `${d.file}.${lang}.md`);
    if (!existsSync(source)) continue;
    const md = readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
    const updatedMatch = /Last updated:\s*(.+)/.exec(md);
    const title = d.titles[lang];
    const out = `${d.file}${lang === 'en' ? '' : `.${lang}`}.html`;
    writeFileSync(join(htmlDir, out), page(lang, d.file, title, markdownToHtml(md)));
    written.push(out);
    generated[d.key][lang] = { title, updated: updatedMatch ? updatedMatch[1].trim() : '', markdown: md };
  }
  if (!generated[d.key].en) throw new Error(`legal/${d.file}.md (English) is required`);
}

const ts = `// Generated by scripts/build-legal.mjs from legal/*.md. Do not edit by hand.
import type { Lang } from '@/i18n';

export interface LegalDoc {
  title: string;
  updated: string;
  markdown: string;
}

/** Each document in every language that has a translation; English is always present. */
export const LEGAL_DOCS: Record<'privacy' | 'terms', { en: LegalDoc } & Partial<Record<Lang, LegalDoc>>> = ${JSON.stringify(generated, null, 2)};
`;
mkdirSync(join(root, 'src', 'content'), { recursive: true });
writeFileSync(join(root, 'src', 'content', 'legal.generated.ts'), ts);
console.log(`Wrote ${written.join(', ')} and src/content/legal.generated.ts`);
